#!/usr/bin/env python3
"""Public, non-sensitive Granite Speech 5.0 smoke test.

Runs real IBM model inference on a generic synthetic fixture. Never imports,
sends, or prints the unpublished BOSS manuscript or private audio.
"""
import hashlib
import json
import os
from pathlib import Path
import sys
import time
import wave

REFERENCE = "The shipping label does not prove delivery. The package requires independent inspection."
MODEL_ID = "ibm-granite/granite-speech-5.0-2b"
PROMPTS = {
    "ordinary": "<|audio|>transcribe the speech with proper punctuation and capitalization.",
    "keyword_bias": "<|audio|>transcribe the speech to text. Keywords: label, delivery, package, inspection.",
}

def score(ref, hyp):
    import re
    from difflib import SequenceMatcher
    canon=lambda s: re.findall(r"[a-z0-9]+",s.lower())
    a,b=canon(ref),canon(hyp)
    c={"equal":0,"replace":0,"delete":0,"insert":0}
    for opcode, a1,a2,b1,b2 in SequenceMatcher(None,a,b,autojunk=False).get_opcodes():
        if opcode=="equal": continue
        if opcode=="replace":
            common=min(a2-a1,b2-b1)
            c["replace"]+=common
            c["delete"]+=(a2-a1-common)
            c["insert"]+=(b2-b1-common)
        elif opcode=="delete": c["delete"]+=a2-a1
        elif opcode=="insert": c["insert"]+=b2-b1
    distance=c["replace"]+c["delete"]+c["insert"]
    critical={word:{"expected":a.count(word),"actual":b.count(word)} for word in ("not","requires","delivery") if a.count(word)}
    return {"reference_words":len(a),"wer_approx":round(distance/len(a),4),"edits":c,"critical_terms":critical}

def main():
    import numpy as np
    import torch
    import soundfile as sf
    import transformers
    from transformers import AutoModelForSpeechSeq2Seq, AutoProcessor

    wav=Path("public_synthetic_16k.wav")
    if not wav.is_file():
        raise FileNotFoundError("Generic public synthetic fixture not generated by CI")
    with wave.open(str(wav),"rb") as w:
        if w.getnchannels()!=1 or w.getframerate()!=16000 or w.getsampwidth()!=2:
            raise ValueError("WAV must be 16-kHz mono 16-bit")
    data,sr=sf.read(str(wav),dtype="float32")
    if data.ndim != 1 or sr!=16000:
        raise ValueError("Expected mono 16k audio")
    torch.set_num_threads(4)
    print("Starting model download/load; no private BOSS data used",flush=True)
    started=time.monotonic()
    processor=AutoProcessor.from_pretrained(MODEL_ID)
    tokenizer=processor.tokenizer
    model=AutoModelForSpeechSeq2Seq.from_pretrained(
        MODEL_ID, device_map="cpu", torch_dtype=torch.bfloat16
    )
    model.eval()
    print(f"Model loaded in {time.monotonic()-started:.1f}s",flush=True)
    audio=torch.from_numpy(data).unsqueeze(0)
    results={"model":MODEL_ID,"fixture_kind":"PUBLIC_GENERIC_SYNTHETIC",
             "audio_sha256":hashlib.sha256(wav.read_bytes()).hexdigest(),
             "duration_sec":len(data)/sr,
             "device":"cpu","torch":torch.__version__,
             "transformers":transformers.__version__,
             "runs":[],"private_boss_content_included":False}
    for label,user_prompt in PROMPTS.items():
        chat=[{"role":"user","content":user_prompt}]
        prompt=tokenizer.apply_chat_template(chat,tokenize=False,add_generation_prompt=True)
        inputs=processor(prompt,audio,device="cpu",return_tensors="pt").to("cpu")
        start=time.monotonic()
        with torch.inference_mode():
            generated=model.generate(**inputs,max_new_tokens=110,do_sample=False,num_beams=1)
        elapsed=time.monotonic()-start
        num_input=inputs["input_ids"].shape[-1]
        hyp=tokenizer.batch_decode(generated[:,num_input:],add_special_tokens=False,skip_special_tokens=True)[0].strip()
        record={"case_id":"public_negation","condition":label,"elapsed_sec":round(elapsed,3),
                "reference":REFERENCE,"hypothesis":hyp,"score":score(REFERENCE,hyp)}
        results["runs"].append(record)
        print(json.dumps(record,ensure_ascii=False),flush=True)

    # Newly authored public sentence tests specialist terms; no user manuscript text.
    term_reference="Bioscillate uses IPOS, PARCELS, and PRIME at Main Street Copy."
    term_wav=Path("public_terms_16k.wav")
    with wave.open(str(term_wav),"rb") as w:
        if w.getnchannels()!=1 or w.getframerate()!=16000 or w.getsampwidth()!=2:
            raise ValueError("Terminology WAV must be 16-kHz mono 16-bit")
    terms_signal,terms_sr=sf.read(str(term_wav),dtype="float32")
    if terms_signal.ndim!=1 or terms_sr!=16000:
        raise ValueError("Invalid public terminology audio")
    results["public_terms_audio_sha256"]=hashlib.sha256(term_wav.read_bytes()).hexdigest()
    results["public_terms_duration_sec"]=len(terms_signal)/terms_sr
    terms_audio=torch.from_numpy(terms_signal).unsqueeze(0)
    term_prompts={
        "ordinary":"<|audio|>transcribe the speech with proper punctuation and capitalization.",
        "keyword_bias":"<|audio|>transcribe the speech to text. Keywords: Bioscillate, IPOS, PARCELS, PRIME, Main Street Copy."
    }
    for label,user_prompt in term_prompts.items():
        chat=[{"role":"user","content":user_prompt}]
        prompt=tokenizer.apply_chat_template(chat,tokenize=False,add_generation_prompt=True)
        inputs=processor(prompt,terms_audio,device="cpu",return_tensors="pt").to("cpu")
        start=time.monotonic()
        with torch.inference_mode():
            generated=model.generate(**inputs,max_new_tokens=110,do_sample=False,num_beams=1)
        elapsed=time.monotonic()-start
        num_input=inputs["input_ids"].shape[-1]
        hyp=tokenizer.batch_decode(generated[:,num_input:],add_special_tokens=False,skip_special_tokens=True)[0].strip()
        record={"case_id":"public_boss_terms","condition":label,"elapsed_sec":round(elapsed,3),
                "reference":term_reference,"hypothesis":hyp,"score":score(term_reference,hyp)}
        results["runs"].append(record)
        print(json.dumps(record,ensure_ascii=False),flush=True)
    Path("granite_public_smoke_results.json").write_text(json.dumps(results,indent=2))
    print("REAL_GRANITE_INFERENCE_EXECUTED",flush=True)

if __name__=="__main__":
    main()
